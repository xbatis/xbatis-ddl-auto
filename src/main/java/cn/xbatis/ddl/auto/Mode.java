package cn.xbatis.ddl.auto;

/**
 * 自动建表模式。
 */
public enum Mode {
    /**
     * 无，就是不做处理
     */
    NONE,

    /**
     * 仅在表不存在时创建表；表已存在时不做任何变更。
     */
    CREATE,

    /**
     * 表不存在时创建表；表已存在时只追加实体中新增的字段。
     * <p>
     * 出于数据安全考虑，该模式不会自动删除字段、修改字段类型、修改字段长度或重命名字段。
     */
    UPDATE,

    /**
     * 表不存在时创建表；表已存在时会删除数据库中多余的列和索引，并补齐实体中缺失的列和索引。
     * <p>
     * 会修改字段类型、字段长度和默认值；仍不会自动修改字段是否可空、重命名字段或删除表。
     */
    SYNC
}
